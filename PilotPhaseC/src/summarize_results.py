"""
Regenerate PilotPhaseC/results/RESULTS_SUMMARY.md from every manifest.json under results/.

Run from the m3x repo root:
    .venv/bin/python -m PilotPhaseC.src.summarize_results
"""

from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

_ROOT = Path(__file__).resolve().parents[2]
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

from PilotPhaseC.config import RESULTS_DIR

# Runs trained before label modes / load specs existed (Ring 1, 2026-10-23).
_LEGACY_PIPELINE_NOTE = (
    "Trained 2026-10-23 with the earlier pipeline (no `label_mode`; period weights all 1.0; "
    "labels 4-class only). Kept for reference; not directly comparable to the newer runs."
)

_PARTICIPANT_ORDER = {"ring01_pid104": 0, "ring03_pid102": 1, "ring04_pid101": 2, "generalized": 3}


def _load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def _pct(x) -> str:
    return "—" if x is None else f"{100 * x:.1f}%"


def _row_key(rel: Path, m: dict):
    return (
        _PARTICIPANT_ORDER.get(rel.parts[0], 99),
        rel.parts[1],
        0 if m.get("label_mode") == "four_class" else 1,
    )


def _classification_rows(entries: list[tuple[Path, dict]]) -> list[str]:
    lines = [
        "| Participant | Label mode | Windows | Survey groups | CV folds | "
        "Accuracy, fold mean ± std | Accuracy, pooled | Macro F1, pooled | Results folder |",
        "|---|---|---:|---:|---:|---|---:|---:|---|",
    ]
    for rel, m in entries:
        cv = m["cv_metrics"]
        pooled = cv.get("pooled_oof", {})
        mode = "4-class" if m.get("label_mode") == "four_class" else "2-class (good/bad)"
        lines.append(
            f"| {rel.parts[0]} | {mode} | {m['n_windows']:,} | {m['n_groups']} | {m['n_folds']} | "
            f"{_pct(cv.get('fold_mean_accuracy'))} ± {100 * cv.get('fold_std_accuracy', 0):.1f} | "
            f"{_pct(pooled.get('accuracy'))} | {pooled.get('f1_macro', 0):.3f} | `{rel}` |"
        )
    return lines


def _old_ring1_rows(entries: list[tuple[Path, dict]]) -> list[str]:
    lines = [
        "| Lineage | Task | Windows | Survey groups | CV folds | Pooled metrics | Results folder |",
        "|---|---|---:|---:|---:|---|---|",
    ]
    for rel, m in entries:
        pooled = m["cv_metrics"].get("pooled_oof", {})
        if m["task"] == "classification":
            metrics = f"accuracy {_pct(pooled.get('accuracy'))}, macro F1 {pooled.get('f1_macro', 0):.3f} (4-class)"
        else:
            metrics = (
                f"MAE {pooled.get('mae', 0):.2f}, RMSE {pooled.get('rmse', 0):.2f}, "
                f"R² {pooled.get('r2', 0):.3f}"
            )
        lines.append(
            f"| {rel.parts[1]} | {m['task']} | {m['n_windows']:,} | {m['n_groups']} | "
            f"{m['n_folds']} | {metrics} | `{rel}` |"
        )
    return lines


def main():
    entries = [(p.parent.relative_to(RESULTS_DIR), _load(p)) for p in sorted(RESULTS_DIR.glob("**/manifest.json"))]
    new_cls = sorted(
        [(r, m) for r, m in entries if m.get("task") == "classification" and "label_mode" in m],
        key=lambda e: _row_key(*e),
    )
    old = sorted(
        [(r, m) for r, m in entries if "label_mode" not in m],
        key=lambda e: (e[0].parts[1], e[1]["task"]),
    )

    lines = [
        "# Pilot Phase C — results summary",
        "",
        f"Auto-generated by `src/summarize_results.py` on {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')} "
        f"from {len(entries)} `manifest.json` files. Re-run the script after any training run; do not edit by hand.",
        "",
        "## Current models: Ring 3, Ring 4, generalized (classification only)",
        "",
        "**Data used:** legacy 112-row windows only (`*_new_format*` files are excluded, per team decision). "
        "Lineage `all_continuous`. Period weights apply (0–5 min = 1.0, 5–30 min = 0.75, 30–60 min = 0.50). "
        "No non-wear filtering was applied (0 windows dropped in every run). "
        "Generalized pools Ring 1 + Ring 3 + Ring 4 (13,131 windows).",
        "",
        "**Models:** 1D CNN, always a 4-output head for 4-class runs even when a class is absent from the data; "
        "2-class runs map good = relax + eustress, bad = distress + eustress+distress. "
        "Split is grouped by `Survey_ID` (no survey is split across train and test).",
        "",
        "**How to read the accuracy columns:**",
        "- *Fold mean ± std* is the average over CV folds of the uncalibrated model. It is the more conservative "
        "number, and the std shows how unstable it is across surveys.",
        "- *Pooled* is accuracy over all out-of-fold windows after per-class logit biases are tuned on those same "
        "windows to maximize macro F1. It is optimistic, so use it for ranking models rather than as an expected "
        "deployment accuracy.",
        "",
    ]
    lines += _classification_rows(new_cls)

    lines += [
        "",
        "### Class counts in the training data (4-class support, windows)",
        "",
        "| Participant | relax | eustress | distress | eustress+distress |",
        "|---|---:|---:|---:|---:|",
    ]
    for rel, m in new_cls:
        s = m.get("four_class_support")
        if s:
            lines.append(
                f"| {rel.parts[0]} | {s['relax']:,} | {s['eustress']:,} | {s['distress']:,} | {s['eustress+distress']:,} |"
            )

    best = max(new_cls, key=lambda e: e[1]["cv_metrics"]["pooled_oof"]["accuracy"])
    over70 = [
        r.parts[0] + (" 2-class" if m["label_mode"] == "binary_good_bad" else " 4-class")
        for r, m in new_cls
        if m["cv_metrics"]["pooled_oof"]["accuracy"] >= 0.70
    ]
    lines += [
        "",
        "### Takeaways",
        "",
        f"- Highest pooled accuracy: {best[0].parts[0]} "
        f"{'2-class' if best[1]['label_mode'] == 'binary_good_bad' else '4-class'} "
        f"({_pct(best[1]['cv_metrics']['pooled_oof']['accuracy'])}). "
        f"Runs at or above 70% pooled accuracy: {', '.join(over70) if over70 else 'none'}.",
        "- Ring 3's fold accuracy varies widely (see std) because 4-class labels are dominated by "
        "`eustress+distress` and few surveys carry the other classes.",
        "- Ring 4 2-class and 4-class models are close to chance on fold mean; the 4-class run never predicts "
        "`eustress`.",
        "- The `load_spec` stored in the generalized runs' manifests is a placeholder; the actual data was loaded per "
        "participant as legacy 112-row windows without non-wear filtering.",
    ]

    lines += ["", "## Earlier results: Ring 1 (`ring01_pid104`)", "", _LEGACY_PIPELINE_NOTE, ""]
    lines += _old_ring1_rows(old)
    lines.append("")

    out = RESULTS_DIR / "RESULTS_SUMMARY.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
